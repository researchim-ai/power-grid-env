import {mkdir,readFile,copyFile,writeFile,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {SITE_FILES,SITE_ASSETS,publicConfig} from '../site-config.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),out=path.join(root,'dist');
const config=publicConfig(JSON.parse(await readFile(path.join(root,'site.config.json'),'utf8')),process.env.PGE_STUDIO_URL);
await rm(out,{recursive:true,force:true});await mkdir(path.join(out,'assets'),{recursive:true});
for(const name of SITE_FILES)await copyFile(path.join(root,name),path.join(out,name));
for(const name of SITE_ASSETS)await copyFile(path.join(root,'assets',name),path.join(out,'assets',name));
await writeFile(path.join(out,'site.config.json'),JSON.stringify(config,null,2)+'\n');
console.log('Standalone website built in web/dist. No Studio, solver, API or replay files.');
